<#
.SYNOPSIS
Regenerates Windows app, Store, splash, and ICO assets from AppIcon.svg.
.DESCRIPTION
Requires ImageMagick. Start tile assets are generated by New-TileAssets.ps1.
#>
[CmdletBinding()]
param(
    [string]$OutputDirectory = (Join-Path $PSScriptRoot '../src/Tonarink.App/Assets')
)

$ErrorActionPreference = 'Stop'
$magick = (Get-Command magick -ErrorAction Stop).Source
$source = Join-Path $PSScriptRoot '../src/Tonarink.App/Assets/AppIcon.svg'
$output = (Resolve-Path -LiteralPath $OutputDirectory).Path
$temporary = Join-Path ([IO.Path]::GetTempPath()) ('tonarink-icons-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $temporary | Out-Null
$master = Join-Path $temporary 'master.png'

try {
    & $magick '-background' 'none' '-density' '384' $source '-resize' '1536x1536!' '-strip' "PNG32:$master"
    if ($LASTEXITCODE -ne 0) { throw 'Could not render AppIcon.svg.' }
    $scales = @(100, 125, 150, 200, 400)
    $sizes = @(16, 20, 24, 30, 32, 36, 40, 48, 60, 64, 72, 80, 96, 256)
    $assets = @(
        foreach ($scale in $scales) {
            $suffix = if ($scale -eq 100) { '' } else { ".scale-$scale" }
            @{ Name = "Square44x44Logo$suffix.png"; Size = [int][Math]::Ceiling(44 * $scale / 100.0) }
            @{ Name = "StoreLogo$suffix.png"; Size = [int][Math]::Ceiling(50 * $scale / 100.0) }
        }
        foreach ($size in $sizes) {
            foreach ($suffix in @('', '_altform-unplated', '_altform-lightunplated')) {
                @{ Name = "Square44x44Logo.targetsize-$size$suffix.png"; Size = $size }
            }
        }
    )
    foreach ($asset in $assets) {
        $destination = Join-Path $output $asset.Name
        & $magick $master '-filter' 'Lanczos' '-resize' "$($asset.Size)x$($asset.Size)!" '-strip' '-define' 'png:exclude-chunk=date,time' "PNG32:$destination"
        if ($LASTEXITCODE -ne 0) { throw "Could not generate $destination." }
    }
    foreach ($scale in $scales) {
        $suffix = if ($scale -eq 100) { '' } else { ".scale-$scale" }
        $width = [int][Math]::Ceiling(620 * $scale / 100.0)
        $height = [int][Math]::Ceiling(300 * $scale / 100.0)
        $logoSize = [int][Math]::Ceiling(256 * $scale / 100.0)
        $destination = Join-Path $output "SplashScreen$suffix.png"
        & $magick $master '-filter' 'Lanczos' '-resize' "${logoSize}x${logoSize}!" '-gravity' 'center' '-background' 'none' '-extent' "${width}x${height}" '-strip' '-define' 'png:exclude-chunk=date,time' "PNG32:$destination"
        if ($LASTEXITCODE -ne 0) { throw "Could not generate $destination." }
    }
    & $magick $master '-define' 'icon:auto-resize=256,128,96,64,48,32,24,20,16' (Join-Path $output 'AppIcon.ico')
    if ($LASTEXITCODE -ne 0) { throw 'Could not generate AppIcon.ico.' }
    Write-Host "Generated app icons, Store artwork and splash screens in $output"
}
finally {
    if (Test-Path -LiteralPath $master) { Remove-Item -LiteralPath $master }
    Remove-Item -LiteralPath $temporary
}
