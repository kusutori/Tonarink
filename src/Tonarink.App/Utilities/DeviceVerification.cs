    public static string CombineFingerprints(string localFingerprint, string remoteFingerprint) =>
        string.CompareOrdinal(localFingerprint, remoteFingerprint) <= 0
            ? localFingerprint + remoteFingerprint
            : remoteFingerprint + localFingerprint;

    public static IReadOnlyList<string> GetMaterialIconGlyphs(string combinedFingerprint)
    {
        var digest = SHA256.HashData(Encoding.UTF8.GetBytes(combinedFingerprint));
        var value = new BigInteger(digest.AsSpan(0, 16), isUnsigned: true, isBigEndian: true);
        var alphabet = MaterialIconAlphabet;
        var length = (int)Math.Ceiling(128d * Math.Log(2) / Math.Log(alphabet.Length));
        var result = new string[length];
        var radix = new BigInteger(alphabet.Length);

        for (var index = length - 1; index >= 0; index--)
        {
            result[index] = char.ConvertFromUtf32(alphabet[(int)(value % radix)]);
            value /= radix;
        }

        return result;
    }
